export const DEFAULT_CATEGORY_ICON: IconName = 'tag';

export function isCategoryIconName(value: string): value is IconName {
  return ICON_SET.has(value as IconName);
}

/** Resolve a stored category icon (Feather name or legacy emoji) to a Feather icon. */
export function resolveCategoryIcon(icon?: string | null): IconName {
  if (!icon) {
    return DEFAULT_CATEGORY_ICON;
  }
  if (isCategoryIconName(icon)) {
    return icon;
  }
  return EMOJI_TO_ICON[icon] ?? DEFAULT_CATEGORY_ICON;
}
